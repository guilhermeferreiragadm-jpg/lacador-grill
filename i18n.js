const LANG_STORAGE_KEY = "lacador_lang";
let currentLang = "pt";

function detectLang() {
  const stored = localStorage.getItem(LANG_STORAGE_KEY);
  if (stored === "pt" || stored === "en") return stored;
  const nav = (navigator.language || "en").toLowerCase();
  return nav.startsWith("pt") ? "pt" : "en";
}

/* t("status.closesAt", { time: "8pm" }) */
function t(key, vars) {
  let text = I18N[currentLang][key] ?? I18N.pt[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll("{" + name + "}", value);
    }
  }
  return text;
}

function applyTranslations() {
  document.documentElement.lang = currentLang === "pt" ? "pt-BR" : "en";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    el.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    });
  });

  document.title = t("meta.title");
  document.querySelector('meta[name="description"]')?.setAttribute("content", t("meta.description"));

  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    const active = btn.dataset.langBtn === currentLang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  document.dispatchEvent(new CustomEvent("languagechange", { detail: { lang: currentLang } }));
}

function setLang(lang) {
  if (lang !== "pt" && lang !== "en") return;
  currentLang = lang;
  localStorage.setItem(LANG_STORAGE_KEY, lang);
  applyTranslations();
}

function setupLanguage() {
  currentLang = detectLang();
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.dataset.langBtn));
  });
  applyTranslations();
}
